#!/usr/bin/env bun
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { type Language, type TargetLanguageCode, Translator } from "deepl-node";

const DEEPL_API_KEY = process.env.DEEPL_API_KEY;
const SOURCE_LANG = "en";
const RATE_LIMIT_DELAY = 200;
const LANGUAGE_CONCURRENCY = 10;
const REQUEST_CONCURRENCY = 1;
const RETRANSLATE_SOURCE_MATCH =
  process.env.TRANSLATE_RETRANSLATE_SOURCE_MATCH === "1";
const MAX_RETRIES = 3;
const RETRY_DELAY = 2000;
const LOCALES_MODULE_PATH = join(process.cwd(), "i18n", "locales.ts");

if (!DEEPL_API_KEY) {
  console.error("❌ DEEPL_API_KEY not found in environment variables");
  process.exit(1);
}

const translator = new Translator(DEEPL_API_KEY);

const TARGET_LANGS = await translator.getTargetLanguages();

type TranslationValue =
  | string
  | number
  | boolean
  | null
  | { [key: string]: TranslationValue }
  | TranslationValue[];

type TranslationStatus = "updated" | "skipped" | "failed";

type TranslationResult = {
  code: string;
  status: TranslationStatus;
};

function collectAvailableLocales(messagesDir: string): string[] {
  const localeCodes = readdirSync(messagesDir)
    .filter((fileName) => fileName.endsWith(".json"))
    .map((fileName) => fileName.slice(0, -".json".length));

  const uniqueSorted = Array.from(new Set(localeCodes)).sort((a, b) =>
    a.localeCompare(b)
  );

  if (uniqueSorted.includes(SOURCE_LANG)) {
    return [SOURCE_LANG, ...uniqueSorted.filter((code) => code !== SOURCE_LANG)];
  }

  return uniqueSorted;
}

function buildLocalesModuleContent(locales: string[]): string {
  const localeEntries = locales.map((code) => `  "${code}",`).join("\n");

  return `// Auto-generated by scripts/translate.ts. Do not edit manually.\n\nexport const locales = [\n${localeEntries}\n] as const;\n\nexport type AppLocale = (typeof locales)[number];\n`;
}

function syncLocalesModule(messagesDir: string): string[] {
  const locales = collectAvailableLocales(messagesDir);
  const nextContent = buildLocalesModuleContent(locales);

  const currentContent = existsSync(LOCALES_MODULE_PATH)
    ? readFileSync(LOCALES_MODULE_PATH, "utf-8")
    : null;

  if (currentContent !== nextContent) {
    writeFileSync(LOCALES_MODULE_PATH, nextContent);
    console.log(`🗺️  Updated locales module: ${LOCALES_MODULE_PATH}`);
  } else {
    console.log("🗺️  Locales module already up to date");
  }

  return locales;
}

function delay(ms: number): Promise<void> {
  return new Promise((resolve) => setTimeout(resolve, ms));
}

function createLimiter(concurrency: number) {
  let activeCount = 0;
  const queue: Array<() => void> = [];

  const next = () => {
    if (activeCount >= concurrency || queue.length === 0) {
      return;
    }

    activeCount += 1;
    const run = queue.shift();
    run?.();
  };

  return async function limit<T>(task: () => Promise<T>): Promise<T> {
    return new Promise((resolve, reject) => {
      queue.push(() => {
        void task()
          .then(resolve)
          .catch(reject)
          .finally(() => {
            activeCount -= 1;
            next();
          });
      });

      next();
    });
  };
}

const limitTranslationRequest = createLimiter(REQUEST_CONCURRENCY);

async function translateWithRetry(
  text: string,
  targetLang: Language,
  retries = 0
): Promise<string> {
  try {
    if (RATE_LIMIT_DELAY > 0) {
      await delay(RATE_LIMIT_DELAY);
    }

    const result = await limitTranslationRequest(() =>
      translator.translateText(
        text,
        SOURCE_LANG,
        targetLang.code as TargetLanguageCode
      )
    );

    return result.text;
  } catch (error) {
    if (retries < MAX_RETRIES) {
      const waitTime = RETRY_DELAY * (retries + 1);
      console.log(
        `⏳ [${targetLang.code}] Rate limited, waiting ${waitTime}ms before retry ${retries + 1}/${MAX_RETRIES}...`
      );
      await delay(waitTime);
      return translateWithRetry(text, targetLang, retries + 1);
    }
    throw error;
  }
}

function shouldSkipTranslation(
  existing: TranslationValue | null,
  source: string
): boolean {
  return (
    existing !== null &&
    typeof existing === "string" &&
    existing.trim() !== "" &&
    (!RETRANSLATE_SOURCE_MATCH || existing !== source)
  );
}

function getExistingValue(
  existing: TranslationValue | null,
  key: string | number
): TranslationValue | null {
  if (Array.isArray(existing)) {
    return (existing[key as number] ?? null) as TranslationValue | null;
  }

  if (!existing || typeof existing !== "object") {
    return null;
  }

  return (existing as Record<string, unknown>)[key] as TranslationValue | null;
}

function isFullyTranslated(
  source: TranslationValue,
  existing: TranslationValue | null
): boolean {
  if (typeof source === "string") {
    return shouldSkipTranslation(existing, source);
  }

  if (Array.isArray(source)) {
    if (!Array.isArray(existing) || existing.length !== source.length) {
      return false;
    }

    for (let index = 0; index < source.length; index += 1) {
      if (!isFullyTranslated(source[index], existing[index] ?? null)) {
        return false;
      }
    }

    return true;
  }

  if (source && typeof source === "object") {
    if (!existing || typeof existing !== "object" || Array.isArray(existing)) {
      return false;
    }

    for (const key of Object.keys(source)) {
      if (!isFullyTranslated(source[key], getExistingValue(existing, key))) {
        return false;
      }
    }

    return true;
  }

  return source === existing;
}

async function translateString(
  text: string,
  targetLang: Language,
  path: string
): Promise<string> {
  try {
    const result = await translateWithRetry(text, targetLang);
    if (path) {
      console.log(`✓ [${targetLang.code}] Translated: ${path}`);
    }
    return result;
  } catch (error) {
    console.error(`✗ [${targetLang.code}] Failed to translate ${path}:`, error);
    return text;
  }
}

async function translateObject(
  obj: TranslationValue,
  targetLang: Language,
  existing: TranslationValue | null,
  path = ""
): Promise<TranslationValue> {
  if (typeof obj === "string") {
    if (shouldSkipTranslation(existing, obj)) {
      return existing as string;
    }
    return translateString(obj, targetLang, path);
  }

  if (Array.isArray(obj)) {
    const translatedArray: TranslationValue[] = [];

    for (let index = 0; index < obj.length; index += 1) {
      const newPath = path ? `${path}[${index}]` : `[${index}]`;
      translatedArray[index] = await translateObject(
        obj[index],
        targetLang,
        getExistingValue(existing, index),
        newPath
      );
    }

    return translatedArray;
  }

  if (typeof obj === "object" && obj !== null) {
    const translated: Record<string, TranslationValue> = {};

    for (const key in obj) {
      if (Object.hasOwn(obj, key)) {
        const newPath = path ? `${path}.${key}` : key;
        const existingValue = getExistingValue(existing, key);
        translated[key] = await translateObject(
          obj[key],
          targetLang,
          existingValue,
          newPath
        );
      }
    }
    return translated;
  }

  return obj;
}

async function mapLimit<T, R>(
  items: T[],
  concurrency: number,
  mapper: (item: T, index: number) => Promise<R>
): Promise<R[]> {
  if (items.length === 0) {
    return [];
  }

  const workerCount = Math.min(concurrency, items.length);
  const results: R[] = new Array(items.length);
  let currentIndex = 0;

  const workers = Array.from({ length: workerCount }, async () => {
    while (true) {
      const index = currentIndex;
      currentIndex += 1;

      if (index >= items.length) {
        return;
      }

      results[index] = await mapper(items[index], index);
    }
  });

  await Promise.all(workers);
  return results;
}

async function translateLanguage(
  sourceContent: TranslationValue,
  messagesDir: string,
  targetLang: Language
): Promise<TranslationResult> {
  const targetFile = join(messagesDir, `${targetLang.code}.json`);
  let existingContent: TranslationValue | null = null;
  let existingRaw: string | null = null;

  if (existsSync(targetFile)) {
    try {
      existingRaw = readFileSync(targetFile, "utf-8");
      existingContent = JSON.parse(existingRaw) as TranslationValue;

      if (isFullyTranslated(sourceContent, existingContent)) {
        console.log(`⚡ [${targetLang.code}] Already translated, skipping`);
        return { code: targetLang.code, status: "skipped" };
      }

      console.log(`📂 [${targetLang.code}] Found existing translations`);
    } catch {
      console.log(
        `⚠️  [${targetLang.code}] Could not read existing file, regenerating`
      );
    }
  }

  const translatedContent = await translateObject(
    sourceContent,
    targetLang,
    existingContent
  );

  const serialized = `${JSON.stringify(translatedContent, null, 2)}\n`;

  if (serialized === existingRaw) {
    console.log(`⚡ [${targetLang.code}] No content changes, skipping write`);
    return { code: targetLang.code, status: "skipped" };
  }

  writeFileSync(targetFile, serialized);
  console.log(`✅ [${targetLang.code}] Translation complete`);
  console.log(`📄 Updated: ${targetFile}`);

  return { code: targetLang.code, status: "updated" };
}

async function main() {
  const messagesDir = join(process.cwd(), "messages");
  const sourceFile = join(messagesDir, `${SOURCE_LANG}.json`);
  const runTargetLangs = TARGET_LANGS.filter(
    (lang) => lang.code.toLowerCase() !== SOURCE_LANG
  );

  console.log("🌍 Starting translation process...");
  console.log(`📖 Source: ${sourceFile}`);
  console.log(
    `🎯 Target languages (${runTargetLangs.length}): ${runTargetLangs.map((l) => l.code).join(", ")}`
  );
  console.log(
    `⚙️  Concurrency: languages=${LANGUAGE_CONCURRENCY}, requests=${REQUEST_CONCURRENCY}\n`
  );
  console.log(
    `🧠 Skip strategy: ${
      RETRANSLATE_SOURCE_MATCH
        ? "strict (retranslate values equal to source)"
        : "fast (skip any existing non-empty value)"
    }\n`
  );

  const sourceContent = JSON.parse(readFileSync(sourceFile, "utf-8")) as
    TranslationValue;

  const results = await mapLimit(
    runTargetLangs,
    LANGUAGE_CONCURRENCY,
    async (targetLang) => {
      console.log(`🔄 [${targetLang.code}] Starting`);

      try {
        return await translateLanguage(sourceContent, messagesDir, targetLang);
      } catch (error) {
        console.error(`✗ [${targetLang.code}] Translation failed:`, error);
        return {
          code: targetLang.code,
          status: "failed",
        } as TranslationResult;
      }
    }
  );

  const summary = results.reduce(
    (acc, result) => {
      acc[result.status] += 1;
      return acc;
    },
    {
      updated: 0,
      skipped: 0,
      failed: 0,
    } as Record<TranslationStatus, number>
  );

  console.log("\n🎉 Translation run complete!");
  console.log(`• Updated: ${summary.updated}`);
  console.log(`• Skipped: ${summary.skipped}`);
  console.log(`• Failed: ${summary.failed}`);

  const availableLocales = syncLocalesModule(messagesDir);
  console.log(`• Locales available: ${availableLocales.length}`);

  if (summary.failed > 0) {
    process.exitCode = 1;
  }
}

main().catch((error) => {
  console.error("❌ Translation failed:", error);
  process.exit(1);
});
